      if (('\t' <= lookahead && lookahead <= '\f') ||
          lookahead == ' ') ADVANCE(22);
      if (lookahead != 0) ADVANCE(23);
      END_STATE();
    case 5:
      if (lookahead == '*') ADVANCE(9);
      if (lookahead == ']') ADVANCE(17);
      if (lookahead == '_') ADVANCE(10);
